def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def find_template(root):
    for dp, _, files in os.walk(root):
        if '__pycache__' in dp:
            continue
        for fn in files:
            if fn.endswith('.html'):
                p = os.path.join(dp, fn)
                try:
                    if 'id="expenseAnalysisModal"' in read(p):
                        return p
                except Exception:
                    pass
    return None


def main():
    root = os.getcwd()
    if not os.path.exists(os.path.join(root, 'manage.py')):
        print("!! Run from the project root (the folder with manage.py).")
        sys.exit(1)

    tpl = find_template(root)
    if not tpl:
        print("!! No template contains the Analysis modal. Run "
              "install_analysis_modal.py first.")
        sys.exit(1)
    print("Template: " + tpl + (" (dry run)" if DRY else ""))
    text = read(tpl)

    key = text.find('EXPENSES vs RENT')
    start = text.rfind('<!--', 0, key) if key != -1 else -1
    end = text.rfind('{% endblock %}')
    if start == -1 or end == -1 or start >= end:
        print("!! Couldn't locate the existing Analysis block boundaries. "
              "Nothing changed.")
        sys.exit(1)

    new_text = text[:start] + NEW_BLOCK + "\n\n" + text[end:]
    if new_text == text:
        print("   [skip] already up to date.")
        return
    if DRY:
        print("   [dry-run] would replace the Analysis modal block "
              "(%d chars -> %d chars). Nothing written." % (end - start, len(NEW_BLOCK)))
        return

    bak = tpl + '.bak_analysis_v2'
    if not os.path.exists(bak):
        with open(bak, 'w', encoding='utf-8') as f:
            f.write(text)
    with open(tpl, 'w', encoding='utf-8') as f:
        f.write(new_text)
    print("   [OK] Analysis modal upgraded (backup: " +
          os.path.basename(tpl) + ".bak_analysis_v2)")
    print("\nDone. Hard-refresh the Expenses page and reopen Analysis.")


if __name__ == '__main__':
    main()
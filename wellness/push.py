# -*- coding: utf-8 -*-
"""wellness/push.py - WL-4b, 30 Oct 2026. Sending to a phone (web push).

THE KEYS ARE TWO RAILWAY VARIABLES, generated by Demetri on his laptop and
never passed through chat (as with the journal key):

    WELLNESS_VAPID_PUBLIC   - given to each phone when it subscribes
    WELLNESS_VAPID_PRIVATE  - signs every message, so the push services
                              know it really comes from alivente.online

Without them reminders simply do not run, and Wellness settings says so -
nothing else changes. WELLNESS_VAPID_SUB is the contact the push services
may write to (defaults to the house address).

WHAT A REMINDER SAYS IS DECIDED IN reminders.py, never here: this module
only carries a title, a line and a page to open.
"""
import base64
import hashlib
import json
import logging
import os

from django.utils import timezone

logger = logging.getLogger(__name__)

PUBLIC = 'WELLNESS_VAPID_PUBLIC'
PRIVATE = 'WELLNESS_VAPID_PRIVATE'
SUB = 'WELLNESS_VAPID_SUB'
DEFAULT_SUB = 'mailto:demetrimanias@gmail.com'
# Gone for good: the phone unsubscribed or the app was removed.
GONE = (404, 410)
MAX_FAILURES = 5


def public_key():
    return os.environ.get(PUBLIC, '').strip()


def configured():
    return bool(public_key() and os.environ.get(PRIVATE, '').strip())


def endpoint_hash(endpoint):
    return hashlib.sha256(endpoint.encode('utf-8')).hexdigest()


def subscribe(user, sub, label=''):
    """Keep (or refresh) the phone `sub` = {"endpoint", "keys": {"p256dh",
    "auth"}} for `user`. Returns the device, or None if it is not one."""
    from .models import PushDevice
    endpoint = (sub or {}).get('endpoint') or ''
    keys = (sub or {}).get('keys') or {}
    p256dh, auth = keys.get('p256dh') or '', keys.get('auth') or ''
    if not endpoint.startswith('https://') or not p256dh or not auth or \
            len(p256dh) > 255 or len(auth) > 64 or len(endpoint) > 2000:
        return None
    h = endpoint_hash(endpoint)
    dev = PushDevice.objects.filter(endpoint_hash=h).first()
    if dev is None:
        dev = PushDevice(endpoint_hash=h)
    # A phone handed to someone else re-subscribes under its new owner.
    dev.user = user
    dev.endpoint = endpoint
    dev.p256dh = p256dh
    dev.auth = auth
    dev.label = (label or '')[:80]
    dev.failures = 0
    dev.save()
    return dev


def unsubscribe(user, endpoint):
    from .models import PushDevice
    return PushDevice.objects.filter(
        user=user, endpoint_hash=endpoint_hash(endpoint or '')).delete()[0]


def _vapid():
    # RFC 8292 ("vapid t=..., k=..."), which Apple's push service requires
    # and Google's accepts.
    from py_vapid import Vapid02
    return Vapid02.from_raw(os.environ.get(PRIVATE, '').strip().encode())


def send(device, title, body, url='/wellness/', tag='wellness'):
    """One message to one phone. True when the push service took it."""
    if not configured():
        return False
    from pywebpush import WebPushException, webpush
    payload = json.dumps({'title': title, 'body': body, 'url': url,
                          'tag': tag})
    try:
        webpush(subscription_info={'endpoint': device.endpoint,
                                   'keys': {'p256dh': device.p256dh,
                                            'auth': device.auth}},
                data=payload, vapid_private_key=_vapid(),
                vapid_claims={'sub': os.environ.get(SUB, '').strip()
                              or DEFAULT_SUB},
                ttl=3600, timeout=20)
    except WebPushException as exc:
        status = getattr(getattr(exc, 'response', None), 'status_code', None)
        if status in GONE:
            device.delete()
        else:
            device.failures += 1
            if device.failures >= MAX_FAILURES:
                device.delete()
            else:
                device.save(update_fields=['failures'])
        logger.warning('Wellness push failed (%s)', status)
        return False
    except Exception as exc:                              # noqa: BLE001
        logger.warning('Wellness push failed: %s', exc)
        return False
    device.last_ok_at = timezone.now()
    device.failures = 0
    device.save(update_fields=['last_ok_at', 'failures'])
    return True


def send_to_user(user, title, body, url='/wellness/', tag='wellness'):
    """To every phone the person allowed. Returns how many took it."""
    from .models import PushDevice
    return sum(1 for d in list(PushDevice.objects.filter(user=user))
               if send(d, title, body, url, tag))


def raw_key_words(b64):
    """The public key as a phone wants it (urlsafe base64, no padding)."""
    return (b64 or '').strip().rstrip('=')


def looks_like_key(b64):
    try:
        raw = base64.urlsafe_b64decode(b64 + '=' * (-len(b64) % 4))
    except Exception:                                     # noqa: BLE001
        return False
    return len(raw) == 65 and raw[0] == 4
